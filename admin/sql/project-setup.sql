begin;
create table if not exists public.status_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  color text not null default '#22c55e' check (color ~ '^#[0-9A-Fa-f]{6}$'),
  active boolean not null default true,
  sort_order integer not null default 0
);
create table if not exists public.apartments (
  id bigint generated by default as identity primary key,
  tower text not null,
  floor integer not null,
  unit integer not null,
  status text not null default 'Available',
  buyer_name text not null default '',
  buyer_number text not null default '',
  updated_at timestamptz not null default now(),
  unique(tower,floor,unit)
);
create table if not exists public.visitors (
  id bigint generated by default as identity primary key,
  name text not null check(length(trim(name)) > 0),
  first_name text not null default '', last_name text not null default '',
  mobile text not null check(mobile ~ '^[0-9]{10}$'), phone text,
  dial_code text not null default '+91', email text not null default '',
  city text not null check(length(trim(city)) > 0), source_page text,
  created_at timestamptz not null default now()
);
create table if not exists public.hold_requests (
  id bigint generated by default as identity primary key,
  visitor_name text not null, visitor_mobile text not null,
  visitor_email text not null default '', visitor_city text not null default '',
  tower text not null, floor integer not null, unit integer not null,
  apartment_detail text not null,
  status text not null default 'pending' check(status in ('pending','approved','rejected')),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
insert into public.status_categories(name,color,sort_order) values
  ('Available','#22c55e',0),('Sold','#ef4444',1),('On Hold','#f59e0b',2)
  on conflict(name) do nothing;

-- Every signed-in Auth account has admin access, as requested by the owner.
create or replace function public.is_cm_admin() returns boolean
language sql stable set search_path = '' as $$
  select coalesce(auth.jwt()->>'role' = 'authenticated', false)
$$;
do $$ declare t text; begin
  foreach t in array array['status_categories','apartments','visitors','hold_requests'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format('drop policy if exists cm_admin_manage on public.%I',t);
    execute format('create policy cm_admin_manage on public.%I for all to authenticated using (public.is_cm_admin()) with check (public.is_cm_admin())',t);
  end loop;
end $$;
grant usage, select on sequence public.status_categories_id_seq, public.apartments_id_seq, public.visitors_id_seq, public.hold_requests_id_seq to authenticated;
grant insert on public.visitors, public.hold_requests to anon;
grant usage on sequence public.visitors_id_seq, public.hold_requests_id_seq to anon;
drop policy if exists cm_public_register on public.visitors;
drop policy if exists cm_public_hold on public.hold_requests;
create policy cm_public_register on public.visitors for insert to anon with check(true);
create policy cm_public_hold on public.hold_requests for insert to anon with check(status = 'pending');

create or replace function public.delete_plot_status(p_status_id bigint) returns void
language plpgsql security definer set search_path = '' as $$
declare old_name text; begin
  if not public.is_cm_admin() then raise exception 'Admin access required'; end if;
  select name into old_name from public.status_categories where id=p_status_id;
  if lower(old_name)='available' then raise exception 'Available is the default status and cannot be deleted'; end if;
  update public.apartments set status='Available',updated_at=now() where status=old_name;
  delete from public.status_categories where id=p_status_id;
end $$;
revoke all on function public.delete_plot_status(bigint) from public, anon;
grant execute on function public.delete_plot_status(bigint) to authenticated;

create or replace function public.cm_rename_status() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if old.name <> new.name then
    if lower(old.name) = 'available' then raise exception 'Available is the default status and cannot be renamed'; end if;
    update public.apartments set status=new.name,updated_at=now() where status=old.name;
  end if;
  return new;
end $$;
drop trigger if exists cm_status_rename on public.status_categories;
create trigger cm_status_rename after update of name on public.status_categories
for each row execute function public.cm_rename_status();
commit;

